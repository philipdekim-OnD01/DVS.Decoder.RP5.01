from smbus2 import SMBus, i2c_msg

W, H = 960, 720
IPC_RECORD = struct.Struct("<HHB3xQ")
# Browser wire record: x:u16, y:u16, polarity:u8, V4L2 timestamp:u64 (microseconds).
# S5KRC1S polarity is 0=ON and 1=OFF (datasheet section 6.8.2.2.3).
WEB_EVENT = struct.Struct("<HHBQ")
RAW2_BATCH_HEADER = struct.Struct("<4sII")
RAW2_FRAME_HEADER = struct.Struct("<4sIIIQ")
BITS_392C = {"cid": 7, "flip_row": 6, "mirror_column": 5, "merged_group": 3,
             "all_event": 2, "on_event_only": 1, "off_event_only": 0}
READ_REGS = {0x392C, 0x0157, 0x0166, 0x0167, 0x0168, 0x3282, *range(0x3300, 0x330D)}


def monotonic_ns():
    """Match the RP1 CFE V4L2 SOF timestamp generated by ktime_get_ns()."""
    return time.monotonic_ns()


class Metrics:
    def __init__(self):
        self.started = time.monotonic(); self.ipc_status = "unavailable"; self.i2c_status = "unknown"
        self.events = self.on_events = self.off_events = 0
        self.invalid_x = self.invalid_y = self.socket_errors = 0
        self.ws_batches = self.ws_bytes = self.ws_dropped = self.clients = self.peak_eps = 0
        self.rate_events = 0; self.rate_started = time.monotonic(); self.current_eps = 0
        self.latencies = deque(maxlen=4096)
        self.latest_event_timestamp_us = None
        self.timestamp_source = "V4L2 frame-start CLOCK_MONOTONIC (RP1 CFE SOF)"
        self.producer = {}
        self.producer_metrics_age_s = None

    def event(self, latency, polarity, timestamp_us):
        self.events += 1; self.rate_events += 1
        if polarity: self.off_events += 1
        else: self.on_events += 1
        if latency is not None: self.latencies.append(latency)
        self.latest_event_timestamp_us = timestamp_us

    def load_producer(self, path):
        try:
            stat = path.stat()
            self.producer = json.loads(path.read_text(encoding="utf-8"))
            self.producer_metrics_age_s = max(0.0, time.time() - stat.st_mtime)
        except (FileNotFoundError, OSError, ValueError, json.JSONDecodeError) as exc:
            self.producer_metrics_age_s = None
            logging.warning("Producer metrics unavailable: %s", exc)

    def snapshot(self):
        now = time.monotonic(); elapsed = now - self.rate_started
        if elapsed >= 1:
            self.current_eps = round(self.rate_events / elapsed); self.peak_eps = max(self.peak_eps, self.current_eps)
            self.rate_events = 0; self.rate_started = now
        lat = list(self.latencies); ordered = sorted(lat)
        producer_fresh = self.producer_metrics_age_s is not None and self.producer_metrics_age_s <= 3.0
        result = {"type":"stats", "ipc_status":self.ipc_status, "i2c_status":self.i2c_status,
                "uptime_s":round(now-self.started,1), "events":self.events, "events_per_s":self.current_eps,
                "on_events":self.on_events, "off_events":self.off_events,
                "peak_events_per_s":self.peak_eps, "invalid_x":self.invalid_x, "invalid_y":self.invalid_y,
                "socket_receive_errors":self.socket_errors, "ipc_dropped_events":None,
                "websocket_clients":self.clients, "websocket_batches":self.ws_batches,
                "websocket_bytes":self.ws_bytes, "dropped_websocket_batches":self.ws_dropped,
                "latest_event_timestamp_us":self.latest_event_timestamp_us,
                "timestamp_source":self.timestamp_source,
                "producer_status":"active" if producer_fresh else "stale",
                "producer_metrics_age_s":round(self.producer_metrics_age_s,3) if self.producer_metrics_age_s is not None else None,
                "data_type":"RAW8 / CSI-2 DT 0x2A", "mipi_mode":"0x04", "mipi_lanes":4,
                "latency_label":"host IPC / web latency",
                "latency_latest_ms":round(lat[-1],3) if lat else None,
                "latency_median_ms":round(statistics.median(lat),3) if lat else None,
                "latency_p95_ms":round(ordered[min(len(ordered)-1,int(len(ordered)*.95))],3) if lat else None}
        try:
            result["link_freq_hz"] = int(Path("/sys/module/s5krc1s_min/parameters/link_freq_hz").read_text().strip())
        except (FileNotFoundError, OSError, ValueError):
            result["link_freq_hz"] = None
        aliases = {
            "capture_buffers_sec":"capture_fps", "input_MB_sec":"raw_input_MB_sec",
            "invalid_packets":"parser_errors", "ipc_send_failures":"dropped_events",
        }
        for key, value in self.producer.items():
            result[aliases.get(key, key)] = value
        if "raw_input_MB_sec" in result:
            result["raw_bytes_per_sec"] = round(float(result["raw_input_MB_sec"]) * 1024 * 1024)
        return result


class SensorI2C:
    def __init__(self, bus, address): self.bus=bus; self.address=address; self.lock=asyncio.Lock()
    def _read(self, reg):
        write=i2c_msg.write(self.address,[(reg>>8)&255,reg&255]); read=i2c_msg.read(self.address,1)
        with SMBus(self.bus) as bus: bus.i2c_rdwr(write,read)
        return list(read)[0]
    def _write(self, reg, value):
        msg=i2c_msg.write(self.address,[(reg>>8)&255,reg&255,value&255])
        with SMBus(self.bus) as bus: bus.i2c_rdwr(msg)
    async def read(self, reg):
        if reg not in READ_REGS: raise ValueError(f"register 0x{reg:04X} is not whitelisted")
        async with self.lock: return await asyncio.to_thread(self._read,reg)
    async def update_bit(self, reg, name, enabled):
        if reg != 0x392C or name not in BITS_392C or name == "cid":
            raise ValueError("only validated 0x392C bit updates are writable")
        async with self.lock:
            old=await asyncio.to_thread(self._read,reg); bit=BITS_392C[name]
            new=(old|(1<<bit)) if enabled else (old&~(1<<bit))
            if new != old: await asyncio.to_thread(self._write,reg,new)
            readback=await asyncio.to_thread(self._read,reg)
            if readback != new: raise OSError(f"readback mismatch: 0x{new:02X} != 0x{readback:02X}")
            return old,new,readback


def bits_392c(value): return {name:(value>>bit)&1 for name,bit in BITS_392C.items()}


class Bridge(asyncio.DatagramProtocol):
    def __init__(self, metrics, clients, batch_size, flush_ms):
        self.m=metrics; self.clients=clients; self.limit=batch_size*WEB_EVENT.size; self.delay=flush_ms/1000
        self.pending=bytearray(); self.task=None
        self.frame_busy=set()
    def connection_made(self, transport): self.m.ipc_status="connected"; logging.info("DVS IPC bound")
    def connection_lost(self, exc): self.m.ipc_status="unavailable"
    def error_received(self, exc): self.m.socket_errors+=1; logging.warning("IPC error: %s",exc)
    def datagram_received(self,data,addr):
        if len(data) == RAW2_FRAME_HEADER.size + W * H // 4 and data[:4] == b"R2F1":
            _, on_count, off_count, invalid_count, timestamp_us = RAW2_FRAME_HEADER.unpack_from(data)
            host_now = monotonic_ns()
            delta = host_now - timestamp_us * 1000
            latency = delta / 1e6 if 0 <= delta < 60_000_000_000 else None
            record_count = on_count + off_count
            self.m.events += record_count
            self.m.rate_events += record_count
            self.m.on_events += on_count
            self.m.off_events += off_count
            if latency is not None:
                self.m.latencies.append(latency)
            self.m.latest_event_timestamp_us = timestamp_us
            targets=[ws for ws in tuple(self.clients) if ws not in self.frame_busy]
            self.m.ws_dropped += len(self.clients)-len(targets)
            if targets: self.m.ws_batches += 1
            for ws in targets:
                self.frame_busy.add(ws)
                asyncio.create_task(self._send_frame(ws,data))
            return
        if len(data) >= RAW2_BATCH_HEADER.size and data[:4] == b"R2W1":
            _, on_count, off_count = RAW2_BATCH_HEADER.unpack_from(data)
            payload = data[RAW2_BATCH_HEADER.size:]
            record_count = len(payload) // WEB_EVENT.size
            if len(payload) % WEB_EVENT.size or record_count != on_count + off_count:
                self.m.socket_errors += 1
                return
            host_now = monotonic_ns()
            timestamp_us = WEB_EVENT.unpack_from(payload, len(payload) - WEB_EVENT.size)[3] if payload else 0
            delta = host_now - timestamp_us * 1000
            latency = delta / 1e6 if 0 <= delta < 60_000_000_000 else None
            self.m.events += record_count
            self.m.rate_events += record_count
            self.m.on_events += on_count
            self.m.off_events += off_count
            if latency is not None:
                self.m.latencies.append(latency)
            self.m.latest_event_timestamp_us = timestamp_us
            self.pending += payload
            if self.pending and self.task is None:
                self.task = asyncio.create_task(self._flush(self.delay if len(self.pending) < self.limit else 0))
            return
        if len(data)%IPC_RECORD.size: self.m.socket_errors+=1; return
        host_now=monotonic_ns()
        for offset in range(0,len(data),IPC_RECORD.size):
            x,y,polarity,ts=IPC_RECORD.unpack_from(data,offset)
            if x>=W: self.m.invalid_x+=1; continue
            if y>=H: self.m.invalid_y+=1; continue
            delta=host_now-ts; latency=delta/1e6 if 0<=delta<60_000_000_000 else None
            timestamp_us=ts//1000
            self.m.event(latency,polarity,timestamp_us); self.pending += WEB_EVENT.pack(x,y,polarity,timestamp_us)
        if self.pending and self.task is None: self.task=asyncio.create_task(self._flush(self.delay if len(self.pending)<self.limit else 0))
    async def _flush(self,delay):
        try:
            if delay: await asyncio.sleep(delay)
            payload=bytes(self.pending); self.pending.clear()
            if not payload or not self.clients: return
            results=await asyncio.gather(*(ws.send(payload) for ws in tuple(self.clients)),return_exceptions=True)
            failures=sum(isinstance(x,Exception) for x in results)
            self.m.ws_batches+=1; self.m.ws_bytes+=len(payload)*(len(results)-failures); self.m.ws_dropped+=failures
        finally: self.task=None
    async def _send_frame(self,ws,payload):
        try:
            await ws.send(payload)
            self.m.ws_bytes += len(payload)
        except Exception:
            self.m.ws_dropped += 1
        finally:
            self.frame_busy.discard(ws)



class HttpHandler(SimpleHTTPRequestHandler):
    def log_message(self,fmt,*args): logging.info("HTTP "+fmt,*args)
    def do_GET(self):
        if self.path.split("?",1)[0] == "/app.js":
            payload=Path("/home/philip/dvs_raw2_production/app_raw2.js").read_bytes()
            self.send_response(200)
            self.send_header("Content-Type","application/javascript; charset=utf-8")
            self.send_header("Content-Length",str(len(payload)))
            self.end_headers()
            self.wfile.write(payload)
            return
        if self.path.split("?",1)[0].rstrip("/") in {"/dvs-live", "/dvs-live-v2"}:
            self.path="/index.html"
        super().do_GET()
    def end_headers(self):
        self.send_header("Cache-Control","no-store"); self.send_header("X-Content-Type-Options","nosniff"); super().end_headers()


def http_server(directory,host,port):
    def handler(*args,**kwargs): HttpHandler(*args,directory=str(directory),**kwargs)
    server=ThreadingHTTPServer((host,port),handler)
    threading.Thread(target=server.serve_forever,daemon=True).start(); return server


async def run(args):
    clients=set(); video_clients=set(); metrics=Metrics(); sensor=SensorI2C(args.i2c_bus,args.i2c_address)
    ipc=Path(args.ipc_socket); app=Path("/home/philip/dvs_web_app")

    async def reply(ws,obj): await ws.send(json.dumps(obj,separators=(",",":")))
    async def control(ws,text):
        try:
            req=json.loads(text); kind=req.get("type"); reg=int(str(req.get("address","")),0)
            if kind=="reg_read":
                value=await sensor.read(reg); metrics.i2c_status="available"
                out={"type":"reg_read","address":f"0x{reg:04X}","value":f"0x{value:02X}"}
                if reg==0x392C: out["bits"]=bits_392c(value)
                await reply(ws,out)
            elif kind=="reg_update_bit":
                enabled=req.get("enabled")
                if not isinstance(enabled,bool): raise ValueError("enabled must be boolean")
                old,new,readback=await sensor.update_bit(reg,str(req.get("bit","")),enabled); metrics.i2c_status="available"
                await reply(ws,{"type":"reg_write_result","address":f"0x{reg:04X}","bit":req["bit"],
                    "old":f"0x{old:02X}","written":f"0x{new:02X}","readback":f"0x{readback:02X}",
                    "bits":bits_392c(readback),"success":True})
            else: raise ValueError("unsupported control request")
        except Exception as exc:
            if isinstance(exc,OSError): metrics.i2c_status="unavailable"
            await reply(ws,{"type":"error","message":str(exc)})

    async def websocket_handler(ws):
        clients.add(ws); metrics.clients=len(clients); logging.info("WebSocket client connected")
        if ws.request.path.split('?',1)[0] != '/control': video_clients.add(ws)
        try:
            await reply(ws,metrics.snapshot())
            async for message in ws:
                if isinstance(message,str): await control(ws,message)
        finally:
            clients.discard(ws); video_clients.discard(ws); metrics.clients=len(clients)

    async def stats_loop():
        while True:
            await asyncio.sleep(1); metrics.load_producer(Path(args.producer_metrics)); text=json.dumps(metrics.snapshot(),separators=(",",":"))
            if clients: await asyncio.gather(*(ws.send(text) for ws in tuple(clients)),return_exceptions=True)

    async def ipc_loop():
        loop=asyncio.get_running_loop()
        while True:
            transport=None
            try:
                if ipc.exists(): ipc.unlink()
                transport,_=await loop.create_datagram_endpoint(lambda:Bridge(metrics,video_clients,args.batch_size,args.flush_ms),family=socket.AF_UNIX,local_addr=str(ipc))
                os.chmod(ipc,0o660)
                while not transport.is_closing(): await asyncio.sleep(1)
            except asyncio.CancelledError: raise
            except Exception as exc:
                metrics.ipc_status="unavailable"; metrics.socket_errors+=1; logging.error("IPC bind failed: %s",exc); await asyncio.sleep(2)
            finally:
                if transport: transport.close()

    http=http_server(app,args.host,args.http_port)
    logging.info("HTTP http://%s:%d; WebSocket ws://%s:%d",args.host,args.http_port,args.host,args.ws_port)
    try:
        async with websockets.serve(websocket_handler,args.host,args.ws_port,max_size=65536): await asyncio.gather(stats_loop(),ipc_loop())
    finally:
        http.shutdown()
        if ipc.exists(): ipc.unlink()


